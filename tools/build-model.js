#!/usr/bin/env node
/*
 * Builds the ingredient model (model/model.json + model/model.js) from
 * historical menu sheets.
 *
 *   node tools/build-model.js                     # every .csv/.tsv/.xlsx in history/
 *   node tools/build-model.js --include-confirmed # also learn from saved days in data/
 *   node tools/build-model.js --sample            # use the made-up sample data
 *   node tools/build-model.js path/to/file.xlsx   # specific file(s)
 *
 * Expected sheet layout (one row per ingredient per menu; column names are
 * matched loosely, and blank Date/Meal/Thaals/Menu cells inherit the row above):
 *
 *   Date | Meal | Thaals | Menu                          | Ingredient | Qty | Unit
 *   01/04/2026 | Lunch | 74+15 | Aloo Pitha + Dal Gosht + Chawal | Onion | 18 | kg
 *
 * Name variants can be merged in model/aliases.json.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const E = require('../js/engine.js');

const ROOT = path.join(__dirname, '..');
const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith('--')));
let files = args.filter((a) => !a.startsWith('--'));
const isSample = flags.has('--sample');

if (isSample) {
  files = [path.join(__dirname, 'sample', 'sample-history.csv')];
  if (!fs.existsSync(files[0])) {
    const S = require('./make-sample.js');
    fs.mkdirSync(path.dirname(files[0]), { recursive: true });
    fs.writeFileSync(files[0], S.toCsv(S.generate()));
  }
} else if (!files.length) {
  const dir = path.join(ROOT, 'history');
  if (fs.existsSync(dir)) {
    files = fs.readdirSync(dir).filter((f) => /\.(csv|tsv|txt|xlsx|xls)$/i.test(f)).map((f) => path.join(dir, f));
  }
}

function readSheets(file) {
  if (/\.(xlsx|xls)$/i.test(file)) {
    let XLSX;
    try { XLSX = require('xlsx'); } catch (e) {
      console.error('Reading Excel files needs the "xlsx" package. Run:  npm install');
      process.exit(1);
    }
    const wb = XLSX.readFile(file, { cellDates: true });
    return wb.SheetNames.map((name) => ({
      name: `${path.basename(file)} / ${name}`,
      rows: XLSX.utils.sheet_to_json(wb.Sheets[name], { header: 1, defval: '', raw: true })
    }));
  }
  return [{ name: path.basename(file), rows: E.parseDelimited(fs.readFileSync(file, 'utf8')) }];
}

const aliasFile = path.join(ROOT, 'model', 'aliases.json');
const aliases = fs.existsSync(aliasFile) ? JSON.parse(fs.readFileSync(aliasFile, 'utf8')) : {};

let menus = [];
for (const file of files) {
  for (const sheet of readSheets(file)) {
    if (!sheet.rows.length) continue;
    // header = first row that maps at least ingredient + qty
    let headerAt = sheet.rows.findIndex((r) => {
      const m = E.autoMapColumns(r.map(String));
      return m.ingredient != null && m.qty != null;
    });
    if (headerAt < 0) { console.warn(`  ! ${sheet.name}: no header row found (need Ingredient and Qty columns) - skipped`); continue; }
    const rows = sheet.rows.slice(headerAt);
    const mapping = E.autoMapColumns(rows[0].map(String));
    const res = E.rowsToMenus(rows, mapping, { defaultUnit: 'kg', defaultMeal: 'Dinner' });
    console.log(`  ${sheet.name}: ${res.menus.length} menus`);
    res.warnings.slice(0, 5).forEach((w) => console.warn('    ' + w));
    menus = menus.concat(res.menus);
  }
}

if (flags.has('--include-confirmed')) {
  const dataDir = path.join(ROOT, 'data');
  if (fs.existsSync(dataDir)) {
    const days = fs.readdirSync(dataDir).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f))
      .map((f) => JSON.parse(fs.readFileSync(path.join(dataDir, f), 'utf8')));
    const confirmed = E.dayFilesToMenus(days);
    console.log(`  data/: ${confirmed.length} confirmed menus`);
    menus = menus.concat(confirmed);
  }
}

if (!menus.length) {
  console.error('No menus found. Put your history sheet(s) in the history/ folder, or run with --sample.');
  process.exit(1);
}

const model = E.train(menus, {
  aliases,
  sample: isSample,
  source: files.map((f) => path.relative(ROOT, f)).join(', ')
});

fs.mkdirSync(path.join(ROOT, 'model'), { recursive: true });
const json = JSON.stringify(model);
fs.writeFileSync(path.join(ROOT, 'model', 'model.json'), json + '\n');
fs.writeFileSync(path.join(ROOT, 'model', 'model.js'), '/* Generated by tools/build-model.js - do not edit */\nwindow.MAWAID_MODEL = ' + json + ';\n');

const s = model.stats;
console.log(`\nModel built: ${s.menus} menus, ${s.dishes} dishes, ${s.ingredients} ingredients (${s.firstDate} to ${s.lastDate})`);
if (s.avgError != null) console.log(`Average difference between formula and history: ${(s.avgError * 100).toFixed(1)}%`);
const weak = Object.values(model.dishes).filter((d) => d.count < 2).map((d) => d.name);
if (weak.length) console.log(`Dishes made only once (low confidence): ${weak.join(', ')}`);
